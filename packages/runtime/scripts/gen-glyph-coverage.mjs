// Regenerates src/ui/glyphCoverage.ts from the bundled fonts' cmap tables.
// Run after replacing a font in apps/client/public/fonts:
//   node packages/runtime/scripts/gen-glyph-coverage.mjs
// test/fonts.test.ts fails if the generated table is out of date.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readCmap, toRanges } from './font-cmap.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const fontDir = join(here, '../../../apps/client/public/fonts');
const out = join(here, '../src/ui/glyphCoverage.ts');

const read = (f) => readCmap(readFileSync(join(fontDir, f)));
const regular = read('Inter-Regular.ttf');
const semibold = read('Inter-SemiBold.ttf');
// Sans text may use either weight: only code points both weights cover are "covered".
const sans = new Set([...regular].filter((c) => semibold.has(c)));
const mono = read('JetBrainsMono-Regular.ttf');

const fmt = (ranges) => {
  const lines = [];
  for (let i = 0; i < ranges.length; i += 16) lines.push('  ' + ranges.slice(i, i + 16).map((n) => '0x' + n.toString(16)).join(', ') + ',');
  return lines.join('\n');
};

writeFileSync(
  out,
  `// GENERATED by scripts/gen-glyph-coverage.mjs from apps/client/public/fonts — do not edit.
// Inclusive [start, end] code point ranges each bundled font has glyphs for.
// The UiKit replaces anything else before it reaches troika, because troika
// resolves uncovered characters by fetching fallback fonts from a CDN (and
// never finishes typesetting when the headset is offline).

/** Inter Regular ∩ Inter SemiBold. */
export const SANS_RANGES: readonly number[] = [
${fmt(toRanges(sans))}
];

/** JetBrains Mono Regular. */
export const MONO_RANGES: readonly number[] = [
${fmt(toRanges(mono))}
];
`,
);
console.log(`wrote ${out}: sans ${sans.size} code points, mono ${mono.size}`);
